export function collegeProfile(name) {
  for (const [re, kind] of PROFILE_RULES) if (re.test(name || '')) return kind;
  return null;
}

/* Специальности для колледжа: профильные первыми, дальше всё остальное. */
export function collegeSpecialties(name) {
  const kind = collegeProfile(name);
  const first = kind ? SPEC[kind] : [];
  const rest = Object.keys(SPEC).filter(k => k !== kind).flatMap(k => SPEC[k]);
  return [...new Set([...first, ...rest])];
}

