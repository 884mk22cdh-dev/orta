/**
 * Перевод строки, вписанной прямо в код.
 * Нет в таблице или язык русский — возвращаем как есть, ничего не ломая.
 */
export function tr(ru) {
  if (typeof ru !== 'string' || !ru) return ru;
  const table = TABLES[getLang()];
  return (table && table[ru]) || ru;
}

